"use client";

import { useState } from "react";

import { Tab } from "@/lib/types";

import {
  DEFAULT_TAB,
  THEME_MUSIC,
  THEME_MUSIC_DISPLAY_TEXT
} from "@/lib/consts";

import Sidebar from "@/components/layout/sidebar/sidebar";
import Content from "@/components/layout/content/content";
import MusicPlayer from "@/components/layout/music_player/music_player";
import Socials from "@/components/layout/socials/socials";

/*
  REFERENCES:
  -----------
  • Tailwind CSS v4 Cheat Sheet: https://www.creative-tim.com/twcomponents/cheatsheet/tailwind-css-4
  • How to Decide When to Use "use client": https://dev.to/tjcoding/how-to-decide-when-to-use-use-client-2dci
  • Automatically add display flex when flex-col or flex-row class is added #8665: https://github.com/tailwindlabs/tailwindcss/discussions/8665
*/

export default function Home() {
  const [tab, setTab] = useState<Tab>(DEFAULT_TAB);

  function scrollToContent() {
    const content = document.getElementById("content");
    content?.scrollIntoView({ behavior: "smooth" });
  };

  function onTabChange(tab: Tab) {
    setTab(tab);
    scrollToContent();
  };

  return (
    <div
      className="lg:h-screen flex flex-col lg:flex-row">
      <Sidebar
        onTabChange={onTabChange} />

      <div
        className="flex-1 flex flex-col lg:flex-col-reverse">
        <MusicPlayer
          src={THEME_MUSIC}
          title={THEME_MUSIC_DISPLAY_TEXT} />
        
        <Content
          tab={tab}
          onTabChange={onTabChange} />
      </div>

      <Socials />
    </div>
  );
}
